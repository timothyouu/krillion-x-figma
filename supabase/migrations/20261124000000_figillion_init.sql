-- Figillion: initial schema, access rules and RPCs.
-- Run once on a fresh Supabase project (SQL Editor, or `supabase db push`).
--
-- Layout
--   public.games, public.tiers            readable by everyone
--   public.import_prompts/import_answers  CSV landing tables for Ankita's content, locked
--   private.*                             answer key and player data; schema not exposed by the API
--   public.<rpc>()                        the only way the app reads or writes game data

-- ───────────────────────── Extensions and schemas ─────────────────────────

create schema if not exists extensions;
create extension if not exists fuzzystrmatch with schema extensions;  -- levenshtein()

create schema if not exists private;
revoke all on schema private from public;

-- ───────────────────────── Public tables ─────────────────────────

create table public.games (
  id                uuid primary key default gen_random_uuid(),
  slug              text not null unique check (slug ~ '^[a-z0-9-]{1,40}$'),
  title             text not null,
  opens_at          timestamptz not null,
  closes_at         timestamptz not null,
  round_count       int not null default 5  check (round_count between 1 and 20),
  prompt_seconds    int not null default 25 check (prompt_seconds between 5 and 120),
  countdown_seconds int not null default 3  check (countdown_seconds between 0 and 10),
  created_at        timestamptz not null default now(),
  check (closes_at > opens_at)
);

create table public.tiers (
  key         text primary key,
  label       text not null,
  points      int not null check (points > 0),
  description text not null,
  sort_order  int not null unique
);

insert into public.tiers (key, label, points, description, sort_order) values
  ('common',     'Common',     10,  'The answer everyone blurts out.',                         1),
  ('too_clever', 'Too Clever', 15,  'The "obscure" pick that everyone else thought of too.',   2),
  ('uncommon',   'Uncommon',   30,  'Solid. Real Figma users know this one.',                  3),
  ('rare',       'Rare',       60,  'Power-user territory.',                                   4),
  ('deep_cut',   'Deep Cut',   85,  'Seriously deep in the docs.',                             5),
  ('figlion',    'Figlion',    100, 'One in a Figillion.',                                     6);

-- CSV landing tables. Column names match the Google Sheet headers.
create table public.import_prompts (
  id        bigint generated by default as identity primary key,
  game_slug text not null,
  round     int  not null,
  theme     text,
  prompt    text not null
);

create table public.import_answers (
  id        bigint generated by default as identity primary key,
  game_slug text not null,
  round     int  not null,
  answer    text not null,
  aliases   text,          -- separated by |
  tier      text not null, -- key or label, e.g. "deep_cut" or "Deep Cut"
  fun_fact  text
);

-- ───────────────────────── Private tables ─────────────────────────

create table private.prompts (
  id      uuid primary key default gen_random_uuid(),
  game_id uuid not null references public.games (id) on delete cascade,
  round   int  not null,
  theme   text not null default '',
  text    text not null,
  unique (game_id, round)
);

create table private.accepted_answers (
  id        uuid primary key default gen_random_uuid(),
  prompt_id uuid not null references private.prompts (id) on delete cascade,
  answer    text not null,
  aliases   text[] not null default '{}',
  tier      text not null references public.tiers (key),
  fun_fact  text
);
create index on private.accepted_answers (prompt_id);

create table private.players (
  id           uuid primary key default gen_random_uuid(),
  user_id      uuid not null references auth.users (id) on delete cascade,
  game_id      uuid not null references public.games (id) on delete cascade,
  display_name text not null check (char_length(display_name) between 1 and 24),
  figpal_slug  text not null check (figpal_slug ~ '^[a-z0-9-]{1,40}$'),
  score        int  not null default 0,
  joined_at    timestamptz not null default now(),
  finished_at  timestamptz,
  unique (user_id, game_id)
);
create index on private.players (game_id, score desc, finished_at);

create table private.player_rounds (
  id                 uuid primary key default gen_random_uuid(),
  player_id          uuid not null references private.players (id) on delete cascade,
  prompt_id          uuid not null references private.prompts (id) on delete cascade,
  round              int  not null,
  started_at         timestamptz not null default now(),
  clock_starts_at    timestamptz not null,
  deadline           timestamptz not null,
  resolved_at        timestamptz,
  accepted_answer_id uuid references private.accepted_answers (id) on delete set null,
  tier               text references public.tiers (key),
  points             int not null default 0,
  final_input        text,
  unique (player_id, round)
);

create table private.attempts (
  id                bigint generated always as identity primary key,
  player_round_id   uuid not null references private.player_rounds (id) on delete cascade,
  raw_answer        text not null,
  normalized        text not null,
  matched_answer_id uuid references private.accepted_answers (id) on delete set null,
  accepted          boolean not null,
  created_at        timestamptz not null default now()
);
create index on private.attempts (player_round_id);

-- ───────────────────────── Access rules ─────────────────────────

alter table public.games          enable row level security;
alter table public.tiers          enable row level security;
alter table public.import_prompts enable row level security;
alter table public.import_answers enable row level security;

create policy "games are public" on public.games for select to anon, authenticated using (true);
create policy "tiers are public" on public.tiers for select to anon, authenticated using (true);
-- import_* tables: RLS on, no policies, so only the dashboard/postgres role can touch them.

revoke all on public.games, public.tiers, public.import_prompts, public.import_answers
  from anon, authenticated;
grant select on public.games, public.tiers to anon, authenticated;

revoke all on all tables in schema private from public, anon, authenticated;

-- ───────────────────────── Private helpers ─────────────────────────

-- Lowercase, unify modifier-key spellings, turn punctuation and "+" into spaces.
create or replace function private.normalize_answer(p text)
returns text
language sql immutable
set search_path = ''
as $$
  select btrim(
    regexp_replace(
      regexp_replace(
        regexp_replace(
          regexp_replace(
            regexp_replace(
              regexp_replace(lower(coalesce(p, '')), '⌘|\mcommand\M', ' cmd ', 'g'),
            '\mcontrol\M', ' ctrl ', 'g'),
          '⌥|\moption\M|\malt\M', ' opt ', 'g'),
        '⇧', ' shift ', 'g'),
      '[^a-z0-9]+', ' ', 'g'),
    '\s+', ' ', 'g'))
$$;

create or replace function private.tier_key(p text)
returns text
language sql immutable
set search_path = ''
as $$
  select regexp_replace(btrim(lower(coalesce(p, ''))), '[\s-]+', '_', 'g')
$$;

create or replace function private.game_by_slug(p_slug text)
returns public.games
language plpgsql stable
set search_path = ''
as $$
declare
  g public.games;
begin
  select * into g from public.games where slug = p_slug;
  if not found then
    raise exception 'game_not_found';
  end if;
  return g;
end;
$$;

create or replace function private.game_status(g public.games)
returns text
language sql stable
set search_path = ''
as $$
  select case
    when now() < g.opens_at   then 'upcoming'
    when now() >= g.closes_at then 'closed'
    else 'open'
  end
$$;

create or replace function private.game_json(g public.games)
returns jsonb
language sql stable
set search_path = ''
as $$
  select jsonb_build_object(
    'slug', g.slug,
    'title', g.title,
    'status', private.game_status(g),
    'opens_at', g.opens_at,
    'closes_at', g.closes_at,
    'round_count', g.round_count,
    'prompt_seconds', g.prompt_seconds,
    'countdown_seconds', g.countdown_seconds,
    'max_score', g.round_count * 100
  )
$$;

create or replace function private.require_player(p_game_id uuid)
returns private.players
language plpgsql stable
set search_path = ''
as $$
declare
  pl private.players;
begin
  if auth.uid() is null then
    raise exception 'not_signed_in';
  end if;
  select * into pl from private.players where game_id = p_game_id and user_id = auth.uid();
  if not found then
    raise exception 'not_joined';
  end if;
  return pl;
end;
$$;

create or replace function private.player_json(p_player_id uuid)
returns jsonb
language sql stable
set search_path = ''
as $$
  select jsonb_build_object(
    'display_name', pl.display_name,
    'figpal_slug', pl.figpal_slug,
    'score', pl.score,
    'depth_m', pl.score * 10,
    'finished', pl.finished_at is not null,
    'rounds_resolved', (
      select count(*) from private.player_rounds pr
      where pr.player_id = pl.id and pr.resolved_at is not null
    )
  )
  from private.players pl
  where pl.id = p_player_id
$$;

create or replace function private.round_json(p_player_round_id uuid)
returns jsonb
language sql stable
set search_path = ''
as $$
  select jsonb_build_object(
    'round', pr.round,
    'resolved', pr.resolved_at is not null,
    'accepted', pr.accepted_answer_id is not null,
    'timed_out', pr.resolved_at is not null and pr.accepted_answer_id is null,
    'answer', a.answer,
    'your_input', pr.final_input,
    'tier', pr.tier,
    'tier_label', t.label,
    'tier_description', t.description,
    'points', pr.points,
    'depth_m', pr.points * 10
  )
  from private.player_rounds pr
  left join private.accepted_answers a on a.id = pr.accepted_answer_id
  left join public.tiers t on t.key = pr.tier
  where pr.id = p_player_round_id
$$;

create or replace function private.finish_if_done(p_player_id uuid)
returns void
language sql
set search_path = ''
as $$
  update private.players pl
     set finished_at = now()
   where pl.id = p_player_id
     and pl.finished_at is null
     and (select count(*) from private.player_rounds pr
           where pr.player_id = pl.id and pr.resolved_at is not null)
         >= (select g.round_count from public.games g where g.id = pl.game_id)
$$;

-- ───────────────────────── Content import (run by Chris in the SQL Editor) ─────────────────────────

-- Validates the rows in public.import_prompts / public.import_answers for one game,
-- replaces that game's prompts and answers, clears the landing rows, and returns a summary.
-- p_force => true also wipes player progress for that game (needed once anyone has played it).
create or replace function private.publish_import(p_game_slug text, p_force boolean default false)
returns jsonb
language plpgsql
set search_path = ''
as $$
declare
  g        public.games;
  v_errors text[] := '{}';
  r        record;
  v_result jsonb;
begin
  g := private.game_by_slug(p_game_slug);

  for r in
    select s.n from generate_series(1, g.round_count) s(n)
    where not exists (select 1 from public.import_prompts ip
                      where ip.game_slug = p_game_slug and ip.round = s.n)
  loop
    v_errors := v_errors || format('round %s: no prompt', r.n);
  end loop;

  for r in
    select ip.round from public.import_prompts ip
    where ip.game_slug = p_game_slug
    group by ip.round
    having count(*) > 1 or ip.round not between 1 and g.round_count
  loop
    v_errors := v_errors || format('round %s: duplicate prompt or round out of range', r.round);
  end loop;

  for r in
    select ia.round, ia.answer, ia.tier from public.import_answers ia
    where ia.game_slug = p_game_slug
      and not exists (select 1 from public.tiers t where t.key = private.tier_key(ia.tier))
  loop
    v_errors := v_errors || format('round %s, "%s": unknown tier "%s"', r.round, r.answer, r.tier);
  end loop;

  for r in
    select ia.round, ia.answer from public.import_answers ia
    where ia.game_slug = p_game_slug
      and not exists (select 1 from public.import_prompts ip
                      where ip.game_slug = ia.game_slug and ip.round = ia.round)
  loop
    v_errors := v_errors || format('round %s, "%s": no prompt for this round', r.round, r.answer);
  end loop;

  for r in
    select s.n from generate_series(1, g.round_count) s(n)
    where not exists (select 1 from public.import_answers ia
                      where ia.game_slug = p_game_slug and ia.round = s.n
                        and private.tier_key(ia.tier) = 'figlion')
  loop
    v_errors := v_errors || format('round %s: needs at least one figlion answer', r.n);
  end loop;

  for r in
    with keys as (
      select ia.round, ia.answer, private.normalize_answer(k) as key
      from public.import_answers ia
      cross join lateral unnest(
        array_prepend(ia.answer, coalesce(string_to_array(ia.aliases, '|'), '{}'::text[]))
      ) as k
      where ia.game_slug = p_game_slug
    )
    select round, key, string_agg(distinct answer, ' / ') as answers
    from keys
    where key <> ''
    group by round, key
    having count(distinct answer) > 1
  loop
    v_errors := v_errors || format('round %s: "%s" matches more than one answer (%s)', r.round, r.key, r.answers);
  end loop;

  if not p_force and exists (
    select 1 from private.player_rounds pr
    join private.prompts p on p.id = pr.prompt_id
    where p.game_id = g.id
  ) then
    v_errors := v_errors || 'players have already started this game; rerun with p_force => true to replace content and reset their progress'::text;
  end if;

  if coalesce(array_length(v_errors, 1), 0) > 0 then
    raise exception E'import failed:\n%', array_to_string(v_errors, E'\n');
  end if;

  if p_force then
    update private.players set score = 0, finished_at = null where game_id = g.id;
  end if;

  delete from private.prompts where game_id = g.id;  -- cascades answers and player rounds

  insert into private.prompts (game_id, round, theme, text)
  select g.id, ip.round, coalesce(btrim(ip.theme), ''), btrim(ip.prompt)
  from public.import_prompts ip
  where ip.game_slug = p_game_slug;

  insert into private.accepted_answers (prompt_id, answer, aliases, tier, fun_fact)
  select p.id,
         btrim(ia.answer),
         coalesce(array(select btrim(x) from unnest(string_to_array(ia.aliases, '|')) x
                        where btrim(x) <> ''), '{}'),
         private.tier_key(ia.tier),
         nullif(btrim(ia.fun_fact), '')
  from public.import_answers ia
  join private.prompts p on p.game_id = g.id and p.round = ia.round
  where ia.game_slug = p_game_slug;

  delete from public.import_answers where game_slug = p_game_slug;
  delete from public.import_prompts where game_slug = p_game_slug;

  select jsonb_agg(x order by (x ->> 'round')::int) into v_result
  from (
    select jsonb_build_object(
      'round', p.round,
      'theme', p.theme,
      'prompt', p.text,
      'answers', count(a.id),
      'by_tier', (select jsonb_object_agg(t.key, (select count(*) from private.accepted_answers a2
                                                  where a2.prompt_id = p.id and a2.tier = t.key))
                  from public.tiers t)
    ) as x
    from private.prompts p
    left join private.accepted_answers a on a.prompt_id = p.id
    where p.game_id = g.id
    group by p.id, p.round, p.theme, p.text
  ) s;

  return jsonb_build_object('game', g.slug, 'rounds', v_result);
end;
$$;

-- ───────────────────────── Public RPCs (called by the app) ─────────────────────────

create or replace function public.get_my_progress(p_game_slug text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  g      public.games;
  v_pid  uuid;
  active jsonb;
begin
  g := private.game_by_slug(p_game_slug);

  select pl.id into v_pid from private.players pl
  where pl.game_id = g.id and pl.user_id = auth.uid();

  if v_pid is not null then
    select jsonb_build_object(
             'round', pr.round, 'theme', p.theme, 'text', p.text,
             'clock_starts_at', pr.clock_starts_at, 'deadline', pr.deadline)
      into active
      from private.player_rounds pr
      join private.prompts p on p.id = pr.prompt_id
     where pr.player_id = v_pid and pr.resolved_at is null;
  end if;

  return jsonb_build_object(
    'server_now', now(),
    'game', private.game_json(g),
    'player', case when v_pid is null then null else private.player_json(v_pid) end,
    'active_round', active
  );
end;
$$;

create or replace function public.join_game(p_game_slug text, p_display_name text, p_figpal_slug text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  g      public.games;
  v_name text := btrim(regexp_replace(coalesce(p_display_name, ''), '\s+', ' ', 'g'));
  v_id   uuid;
begin
  if auth.uid() is null then
    raise exception 'not_signed_in';
  end if;
  g := private.game_by_slug(p_game_slug);
  if private.game_status(g) <> 'open' then
    raise exception 'game_not_open';
  end if;
  if char_length(v_name) not between 1 and 24 then
    raise exception 'invalid_display_name';
  end if;
  if coalesce(p_figpal_slug, '') !~ '^[a-z0-9-]{1,40}$' then
    raise exception 'invalid_figpal';
  end if;

  insert into private.players (user_id, game_id, display_name, figpal_slug)
  values (auth.uid(), g.id, v_name, p_figpal_slug)
  on conflict (user_id, game_id)
    do update set display_name = excluded.display_name, figpal_slug = excluded.figpal_slug
  returning id into v_id;

  return private.player_json(v_id);
end;
$$;

create or replace function public.start_prompt(p_game_slug text, p_round int)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  g  public.games;
  pl private.players;
  pr private.player_rounds;
  p  private.prompts;
begin
  g  := private.game_by_slug(p_game_slug);
  pl := private.require_player(g.id);

  -- One start at a time per player.
  perform 1 from private.players where id = pl.id for update;

  select * into pr from private.player_rounds where player_id = pl.id and round = p_round;

  if not found then
    if private.game_status(g) <> 'open' then
      raise exception 'game_not_open';
    end if;
    if p_round is null or p_round < 1 or p_round > g.round_count then
      raise exception 'invalid_round';
    end if;
    if exists (select 1 from private.player_rounds
               where player_id = pl.id and resolved_at is null) then
      raise exception 'round_in_progress';
    end if;
    if (select count(*) from private.player_rounds
        where player_id = pl.id and round < p_round) <> p_round - 1 then
      raise exception 'round_out_of_order';
    end if;

    select * into p from private.prompts where game_id = g.id and round = p_round;
    if not found then
      raise exception 'prompt_missing';
    end if;

    insert into private.player_rounds (player_id, prompt_id, round, clock_starts_at, deadline)
    values (pl.id, p.id, p_round,
            now() + make_interval(secs => g.countdown_seconds),
            now() + make_interval(secs => g.countdown_seconds + g.prompt_seconds))
    returning * into pr;
  else
    select * into p from private.prompts where id = pr.prompt_id;
  end if;

  return jsonb_build_object(
    'server_now', now(),
    'round', pr.round,
    'round_count', g.round_count,
    'theme', p.theme,
    'text', p.text,
    'clock_starts_at', pr.clock_starts_at,
    'deadline', pr.deadline,
    'resolved', pr.resolved_at is not null
  );
end;
$$;

create or replace function public.submit_answer(p_game_slug text, p_round int, p_answer text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  g           public.games;
  pl          private.players;
  pr          private.player_rounds;
  v_raw       text := left(btrim(coalesce(p_answer, '')), 100);
  v_norm      text;
  v_answer_id uuid;
  v_tier      text;
  v_points    int;
begin
  g  := private.game_by_slug(p_game_slug);
  pl := private.require_player(g.id);

  select * into pr from private.player_rounds
   where player_id = pl.id and round = p_round
   for update;
  if not found then
    raise exception 'round_not_started';
  end if;
  if pr.resolved_at is not null then
    raise exception 'round_already_resolved';
  end if;
  if now() > pr.deadline + interval '2 seconds' then
    raise exception 'time_up';
  end if;
  if (select count(*) from private.attempts where player_round_id = pr.id) >= 30 then
    raise exception 'too_many_attempts';
  end if;

  v_norm := private.normalize_answer(v_raw);
  if v_norm = '' then
    return jsonb_build_object('accepted', false, 'reason', 'empty', 'input', v_raw,
                              'server_now', now(), 'deadline', pr.deadline);
  end if;

  -- Exact match on answer or alias; otherwise 1 edit for inputs of 5+ characters.
  -- Closest wins; ties go to the rarer tier.
  select a.id, a.tier, t.points
    into v_answer_id, v_tier, v_points
    from private.accepted_answers a
    join public.tiers t on t.key = a.tier
    cross join lateral (
      select min(case
                   when private.normalize_answer(x) = v_norm then 0
                   when char_length(private.normalize_answer(x)) > 200 then 99
                   else extensions.levenshtein(private.normalize_answer(x), v_norm)
                 end) as dist
      from unnest(array_prepend(a.answer, a.aliases)) as x
    ) k
   where a.prompt_id = pr.prompt_id
     and (k.dist = 0 or (char_length(v_norm) >= 5 and k.dist <= 1))
   order by k.dist, t.sort_order desc
   limit 1;

  insert into private.attempts (player_round_id, raw_answer, normalized, matched_answer_id, accepted)
  values (pr.id, v_raw, v_norm, v_answer_id, v_answer_id is not null);

  if v_answer_id is null then
    return jsonb_build_object('accepted', false, 'reason', 'no_echo', 'input', v_raw,
                              'server_now', now(), 'deadline', pr.deadline);
  end if;

  update private.player_rounds
     set resolved_at = now(), accepted_answer_id = v_answer_id,
         tier = v_tier, points = v_points, final_input = v_raw
   where id = pr.id;

  update private.players set score = score + v_points where id = pl.id;
  perform private.finish_if_done(pl.id);

  return private.round_json(pr.id) || jsonb_build_object('player', private.player_json(pl.id));
end;
$$;

create or replace function public.finish_prompt(p_game_slug text, p_round int)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  g  public.games;
  pl private.players;
  pr private.player_rounds;
begin
  g  := private.game_by_slug(p_game_slug);
  pl := private.require_player(g.id);

  select * into pr from private.player_rounds
   where player_id = pl.id and round = p_round
   for update;
  if not found then
    raise exception 'round_not_started';
  end if;

  if pr.resolved_at is null then
    if now() < pr.deadline - interval '1 second' then
      raise exception 'time_not_up';
    end if;
    update private.player_rounds set resolved_at = now(), points = 0 where id = pr.id;
    perform private.finish_if_done(pl.id);
  end if;

  return private.round_json(pr.id) || jsonb_build_object('player', private.player_json(pl.id));
end;
$$;

create or replace function public.get_results(p_game_slug text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  g        public.games;
  pl       private.players;
  v_total  int;
  v_below  int;
  v_rank   int;
  v_width  int;
  v_hist   jsonb;
  v_rounds jsonb;
begin
  g  := private.game_by_slug(p_game_slug);
  pl := private.require_player(g.id);
  if pl.finished_at is null then
    raise exception 'not_finished';
  end if;

  select count(*), count(*) filter (where score < pl.score)
    into v_total, v_below
    from private.players
   where game_id = g.id and finished_at is not null;

  select count(*) + 1 into v_rank
    from private.players
   where game_id = g.id and finished_at is not null
     and (score > pl.score or (score = pl.score and finished_at < pl.finished_at));

  v_width := greatest((g.round_count * 100) / 20, 1);
  select jsonb_agg(jsonb_build_object('from', b * v_width, 'to', (b + 1) * v_width - 1,
                                      'count', coalesce(h.c, 0)) order by b)
    into v_hist
    from generate_series(0, 19) b
    left join (
      select least(score / v_width, 19) as bucket, count(*) as c
        from private.players
       where game_id = g.id and finished_at is not null
       group by 1
    ) h on h.bucket = b;

  select jsonb_agg(
           jsonb_build_object('round', p.round, 'theme', p.theme, 'prompt', p.text)
           || coalesce(private.round_json(pr.id), '{}'::jsonb)
           order by p.round)
    into v_rounds
    from private.prompts p
    left join private.player_rounds pr on pr.prompt_id = p.id and pr.player_id = pl.id
   where p.game_id = g.id;

  return jsonb_build_object(
    'player', private.player_json(pl.id),
    'rank', v_rank,
    'finished_count', v_total,
    'better_than_pct', case when v_total <= 1 then 0
                            else round(100.0 * v_below / (v_total - 1)) end,
    'max_score', g.round_count * 100,
    'histogram', v_hist,
    'rounds', v_rounds
  );
end;
$$;

create or replace function public.get_catch(p_game_slug text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  g  public.games;
  pl private.players;
  v  jsonb;
begin
  g  := private.game_by_slug(p_game_slug);
  pl := private.require_player(g.id);
  if pl.finished_at is null then
    raise exception 'not_finished';
  end if;

  select jsonb_agg(
           jsonb_build_object(
             'round', p.round,
             'theme', p.theme,
             'prompt', p.text,
             'answers', (
               select jsonb_agg(jsonb_build_object(
                        'answer', a.answer,
                        'tier', a.tier,
                        'tier_label', t.label,
                        'points', t.points,
                        'fun_fact', a.fun_fact,
                        'yours', coalesce(a.id = pr.accepted_answer_id, false))
                      order by t.sort_order desc, a.answer)
                 from private.accepted_answers a
                 join public.tiers t on t.key = a.tier
                where a.prompt_id = p.id))
           order by p.round)
    into v
    from private.prompts p
    left join private.player_rounds pr on pr.prompt_id = p.id and pr.player_id = pl.id
   where p.game_id = g.id;

  return jsonb_build_object('rounds', coalesce(v, '[]'::jsonb));
end;
$$;

create or replace function public.get_leaderboard(p_game_slug text, p_limit int default 25)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  g        public.games;
  v_limit  int := least(greatest(coalesce(p_limit, 25), 1), 100);
  v_rows   jsonb;
  v_me     jsonb;
  v_total  int;
  v_done   int;
begin
  g := private.game_by_slug(p_game_slug);

  with ranked as (
    select pl.user_id,
           rank() over (order by pl.score desc, pl.finished_at asc nulls last) as rank,
           pl.display_name, pl.figpal_slug, pl.score, pl.score * 10 as depth_m,
           (select count(*) from private.player_rounds pr
             where pr.player_id = pl.id and pr.resolved_at is not null)::int as rounds_done,
           pl.finished_at is not null as finished,
           pl.joined_at
      from private.players pl
     where pl.game_id = g.id
  )
  select
    (select count(*) from ranked),
    (select count(*) from ranked where finished),
    (select jsonb_agg(jsonb_build_object(
              'rank', l.rank, 'display_name', l.display_name, 'figpal_slug', l.figpal_slug,
              'score', l.score, 'depth_m', l.depth_m, 'rounds_done', l.rounds_done,
              'finished', l.finished)
            order by l.rank, l.joined_at)
       from (select * from ranked order by rank, joined_at limit v_limit) l),
    (select jsonb_build_object('rank', m.rank, 'score', m.score, 'depth_m', m.depth_m,
                               'rounds_done', m.rounds_done, 'finished', m.finished)
       from ranked m
      where auth.uid() is not null and m.user_id = auth.uid())
  into v_total, v_done, v_rows, v_me;

  return jsonb_build_object(
    'server_now', now(),
    'total_players', v_total,
    'finished', v_done,
    'diving', v_total - v_done,
    'rows', coalesce(v_rows, '[]'::jsonb),
    'me', v_me
  );
end;
$$;

